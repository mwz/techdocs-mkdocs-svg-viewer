import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const read = (path) => readFile(new URL(path, root), 'utf8');
const overview = (
  await read('examples/mkdocs/docs/observatory.inline.svg')
).replaceAll('processing/', 'processing.html');
const processing = (
  await read('examples/mkdocs/docs/processing.inline.svg')
).replaceAll('../', 'index.html');

// Inline the canonical SVGs so the standalone example also works with file://.
// The checked-in HTML needs no fetch, bundler or local server to display them.
for (const [name, title, diagram, notes] of [
  [
    'index',
    'Space observatory',
    overview,
    `
    <h2 id="data-note">Data note</h2>
    <p>The raw archive retains uncalibrated detector exposures and observation metadata for reprocessing.</p>
    <h2 id="archive-access">Archive access</h2>
    <p>The archive serves raw and calibrated products with quality information, provenance and access rules.</p>`,
  ],
  [
    'processing',
    'Science processing',
    processing,
    `
    <h2 id="calibration">Calibration</h2>
    <p>Apply detector and observing-mode corrections with versioned reference files. Imaging and spectroscopy use different processing branches.</p>
    <h2 id="quality-review">Quality review</h2>
    <p>Record uncertainties, quality flags and provenance. Retain raw data for reprocessing with new software or references.</p>`,
  ],
]) {
  const html = await format(
    `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title} | SVG viewer example</title>
    <!-- Generated by pnpm examples:sync from the MkDocs SVGs. -->
    <!-- Run pnpm build, then open this file or use example:standalone:dev. -->
    <script defer src="../../dist/svg-viewer.js"></script>
    <style>
      body { max-width: 1100px; margin: auto; padding: 24px; font: 16px/1.6 system-ui; color: #192338; background: #f8fafc; }
      body > svg { display: block; width: 100%; height: auto; }
      a { color: #285fa6; }
      nav { display: flex; gap: 24px; }
    </style>
  </head>
  <body>
    <nav aria-label="Examples"><a href="index.html">Observatory overview</a><a href="processing.html">Science processing</a></nav>
    <h1>${title}</h1>
    <p>Expand the diagram, zoom in for detail and drag to pan. Diagram links open pages and sections.</p>
    ${diagram}
    ${notes}
    <p>This is a simplified fictional space mission, informed by <a href="https://jwst-docs.stsci.edu/jwst-science-calibration-pipeline">STScI</a> and <a href="https://science.nasa.gov/asset/webb/how-stsci-sends-commands-to-webb-and-receives-its-data/">NASA</a>.</p>
  </body>
</html>`,
    { parser: 'html', printWidth: 80 },
  );
  const path = `examples/standalone/${name}.html`;
  if (process.argv.includes('--check')) {
    if ((await read(path)) !== html)
      throw new Error(`Run pnpm examples:sync to update ${path}`);
  } else await writeFile(new URL(path, root), html);
}
